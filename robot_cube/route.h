// route.h — маршрут. Это главный файл для подгонки на поле.
//
// Система координат: робот стоит на старте (дальний конец отрезка 2,25 м) лицом вдоль
// зигзага и отрезка 2,38 м, а НЕ вдоль отрезка 2,25 м. За всю поездку он не поворачивается.
//   fwd   > 0 — вперёд, < 0 — назад
//   right > 0 — вправо (в ту сторону, откуда сделано фото с замерами), < 0 — влево
//
// Отрезок длиной L под углом a к направлению «вперёд»:
//   fwd = L * cos(a), right = L * sin(a)
// Для зигзага под 45°: 1,11 * 0,707 = 0,785 м вперёд и 0,785 м вбок.
#pragma once
#include "motion.h"

const Seg ROUTE_TO_ARM[] = {
  //  вперёд   вправо   k
  { 0.00f,   2.25f,  1.0f },    // старт: вбок вправо 2,25 м до начала зигзага
  { 0.785f,  0.785f, 1.0f },    // зигзаг 1: 1,11 м по диагонали вперёд-вправо
  { 0.785f, -0.785f, 1.0f },    // зигзаг 2: 1,11 м вперёд-влево
  { 0.785f,  0.785f, 1.0f },    // зигзаг 3: 1,11 м вперёд-вправо
  { 0.785f, -0.785f, 1.0f },    // зигзаг 4: 1,11 м вперёд-влево
  { 2.38f,   0.00f,  1.0f },    // прямо 2,38 м
  { 0.00f,   3.60f,  1.0f },    // вбок вправо 3,6 м в зону манипулятора
};

